import { crc32, gunzipSync, gzipSync } from "node:zlib";
import { badRequest } from "../../platform/errors.js";

// A generated PDF or PNG carries the series it shows, so it can be imported back:
//   PDF  -> an embedded file attachment ("hok-series.json.gz")
//   PNG  -> a tEXt chunk with keyword "hok-series" (base64 of the same gzip bytes)
// The payload is untrusted on the way back in: it goes through the same strict validation as any
// import
// (validation.js parseSeriesImport), which rebuilds ids, owner, status and drafts on the server.

const FORMAT = "hok-series";
const FORMAT_VERSION = 1;
const ATTACHMENT_NAME = "hok-series.json.gz";
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const MAX_PAYLOAD_BYTES = 8 * 1024 * 1024;
const MAX_SERIES = 100;

/** Only what is needed to restore the series (finished games); the live draft is not part of a file. */
export function buildPayload(
  seriesList,
  { comment = "", exportedAt = new Date().toISOString() } = {}
) {
  return {
    format: FORMAT,
    version: FORMAT_VERSION,
    exportedAt,
    comment,
    series: seriesList.map(series => {
      const {
        currentGame: _live,
        online: _online,
        viewer: _viewer,
        version: _version,
        serverTime: _time,
        ...rest
      } = series;
      return { ...rest, currentGame: null };
    })
  };
}

export const encodePayload = payload =>
  gzipSync(Buffer.from(JSON.stringify(payload), "utf8"), { level: 9 });

/** gzip bytes -> validated envelope. Throws a 400 for anything that is not one of our files. */
export function decodePayload(bytes) {
  let json;
  try {
    json = gunzipSync(bytes, { maxOutputLength: MAX_PAYLOAD_BYTES });
  } catch {
    throw badRequest(
      "This file does not contain HOK series data (or it is damaged).",
      "invalid_file"
    );
  }
  let envelope;
  try {
    envelope = JSON.parse(json.toString("utf8"));
  } catch {
    throw badRequest("This file does not contain readable series data.", "invalid_file");
  }
  if (
    !envelope ||
    envelope.format !== FORMAT ||
    envelope.version !== FORMAT_VERSION ||
    !Array.isArray(envelope.series)
  ) {
    throw badRequest(
      "This file was not generated by HOK Global Scrim Lab, or by an incompatible version.",
      "invalid_file"
    );
  }
  if (!envelope.series.length || envelope.series.length > MAX_SERIES) {
    throw badRequest("A file can restore between 1 and {MAX_SERIES} series.", "invalid_file", {
      MAX_SERIES
    });
  }
  return envelope;
}

// ---- PDF ----------------------------------------------------------------------------------------

// pdf-lib is about 10 MB of memory once loaded, and only a PDF export or import needs it: it is read on the first one.
const loadPdfLib = () => import("pdf-lib");

export async function embedInPdf(
  pdfBuffer,
  payloadBytes,
  { title = "", comment = "", author = "HOK Global Scrim Lab" } = {}
) {
  const { PDFDocument } = await loadPdfLib();
  const document = await PDFDocument.load(pdfBuffer, { updateMetadata: false });
  await document.attach(payloadBytes, ATTACHMENT_NAME, {
    mimeType: "application/gzip",
    description: "Series data to re-import into HOK Global Scrim Lab",
    creationDate: new Date(),
    modificationDate: new Date()
  });
  if (title) {
    document.setTitle(title.slice(0, 120));
  }
  if (comment) {
    document.setSubject(comment.replace(/\s+/g, " ").slice(0, 300));
  }
  document.setAuthor(author);
  document.setCreator("HOK Global Scrim Lab");
  document.setProducer("HOK Global Scrim Lab");
  document.setKeywords(["Honor of Kings Global", "scrim", "draft"]);
  return Buffer.from(await document.save({ useObjectStreams: false }));
}

export async function extractFromPdf(buffer) {
  const { PDFDocument, PDFName, PDFRawStream, decodePDFRawStream } = await loadPdfLib();
  let document;
  try {
    document = await PDFDocument.load(buffer, {
      updateMetadata: false,
      ignoreEncryption: false,
      throwOnInvalidObject: false
    });
  } catch {
    throw badRequest("This PDF cannot be read.", "invalid_file");
  }
  for (const [, object] of document.context.enumerateIndirectObjects()) {
    if (!(object instanceof PDFRawStream)) {
      continue;
    }
    const type = object.dict.get(PDFName.of("Type"));
    if (type?.toString() !== "/EmbeddedFile") {
      continue;
    }
    let bytes;
    try {
      bytes = Buffer.from(decodePDFRawStream(object).decode());
    } catch {
      continue;
    }
    try {
      return decodePayload(bytes);
    } catch {
      /* not ours: try the next attachment */
    }
  }
  throw badRequest(
    "This PDF does not contain HOK series data. Only PDFs generated by this site can be imported (do not re-save or print them).",
    "invalid_file"
  );
}

// ---- PNG ----------------------------------------------------------------------------------------

function pngChunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, "latin1");
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([Buffer.from(type, "latin1"), data])) >>> 0, 0);
  return Buffer.concat([head, data, crc]);
}

function* pngChunks(png) {
  if (png.length < 20 || !png.subarray(0, 8).equals(PNG_SIGNATURE)) {
    throw badRequest("This is not a PNG image.", "invalid_file");
  }
  let offset = 8;
  while (offset + 12 <= png.length) {
    const length = png.readUInt32BE(offset);
    const type = png.toString("latin1", offset + 4, offset + 8);
    if (offset + 12 + length > png.length) {
      throw badRequest("This PNG is truncated.", "invalid_file");
    }
    yield {
      type,
      data: png.subarray(offset + 8, offset + 8 + length),
      start: offset,
      end: offset + 12 + length
    };
    offset += 12 + length;
    if (type === "IEND") {
      return;
    }
  }
}

export function embedInPng(png, payloadBytes) {
  const text = Buffer.concat([
    Buffer.from(`${FORMAT}\0`, "latin1"),
    Buffer.from(payloadBytes.toString("base64"), "latin1")
  ]);
  for (const chunk of pngChunks(png)) {
    if (chunk.type === "IEND") {
      return Buffer.concat([
        png.subarray(0, chunk.start),
        pngChunk("tEXt", text),
        png.subarray(chunk.start)
      ]);
    }
  }
  throw badRequest("This PNG has no end marker.", "invalid_file");
}

export function extractFromPng(png) {
  for (const chunk of pngChunks(png)) {
    if (chunk.type !== "tEXt") {
      continue;
    }
    const separator = chunk.data.indexOf(0);
    if (separator < 0 || chunk.data.toString("latin1", 0, separator) !== FORMAT) {
      continue;
    }
    return decodePayload(Buffer.from(chunk.data.toString("latin1", separator + 1), "base64"));
  }
  throw badRequest(
    "This PNG does not contain HOK series data. Only PNGs generated by this site can be imported (messaging apps and editors strip the data).",
    "invalid_file"
  );
}

/** Detects the file type from its first bytes (the client's Content-Type is not trusted). */
export function sniffFile(buffer) {
  if (buffer.length > 8 && buffer.subarray(0, 8).equals(PNG_SIGNATURE)) {
    return "png";
  }
  if (buffer.length > 5 && buffer.subarray(0, 5).toString("latin1") === "%PDF-") {
    return "pdf";
  }
  return null;
}

export async function extractFromFile(buffer) {
  const kind = sniffFile(buffer);
  if (kind === "pdf") {
    return extractFromPdf(buffer);
  }
  if (kind === "png") {
    return extractFromPng(buffer);
  }
  throw badRequest("Import a PDF or PNG generated by HOK Global Scrim Lab.", "invalid_file");
}

/** Safe download name: letters, digits, space, dot, dash, underscore; never a path. */
export function safeFileName(requested, fallback, extension) {
  const base = String(requested ?? "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\.(pdf|png)$/i, "")
    .replace(/[^A-Za-z0-9 ._-]+/g, "_")
    .replace(/^[ ._-]+|[ ._-]+$/g, "")
    .replace(/\s+/g, " ")
    .slice(0, 80);
  const chosen =
    base ||
    String(fallback)
      .replace(/[^A-Za-z0-9._-]+/g, "_")
      .slice(0, 80) ||
    "series";
  return `${chosen}.${extension}`;
}
