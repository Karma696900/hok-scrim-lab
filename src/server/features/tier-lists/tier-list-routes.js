import { randomUUID } from "node:crypto";
import { Router } from "express";
import { forbidden, notFound } from "../../platform/errors.js";
import { wrap } from "../../platform/http/async.js";
import { normalizeTierList, parseLane, parseTierListInput } from "./tier-list-domain.js";
import { parseExpectedVersion, parsePagination, parseUuid } from "../../platform/validation.js";
import { registerSharingRoutes } from "../sharing/sharing-routes.js";

/**
 * Normalised against the current roster on every read, so new heroes appear in Unranked and legacy
 * ids vanish.
 */
const present = ({ tierList, version, role }, heroes) => ({
  ...normalizeTierList(tierList, heroes),
  version,
  viewer: {
    role,
    canEdit: role === "owner" || role === "editor",
    canDelete: role === "owner",
    canShare: role === "owner"
  }
});

export function createTierListRouter({ store, identity, limiters }) {
  const router = Router();
  const viewerId = request => request.user?.id ?? null;

  router.get(
    "/tier-lists",
    wrap(async request => {
      const paging = parsePagination(request.query, { defaultSize: 50, maxSize: 100 });
      const filters = {};
      if (request.query.lane !== undefined) {
        filters.lane = parseLane(String(request.query.lane));
      }
      if (typeof request.query.q === "string" && request.query.q.trim()) {
        filters.search = request.query.q.trim().slice(0, 80);
      }
      const [{ items, total }, heroes] = await Promise.all([
        store.listTierLists(viewerId(request), { ...paging, ...filters }),
        store.readHeroes()
      ]);
      return {
        items: items.map(item => present(item, heroes)),
        total,
        page: paging.page,
        pageSize: paging.pageSize
      };
    })
  );

  // Ids are generated by the server: a client can no longer create or overwrite an arbitrary id.
  router.post(
    "/tier-lists",
    limiters.createSeries,
    wrap(async (request, response) => {
      const input = parseTierListInput(request.body);
      const heroes = await store.readHeroes();
      const user = await identity.ensureUser(request, response);
      await store.assertQuota("tierList", user);
      const now = new Date().toISOString();
      const tierList = normalizeTierList(
        { id: randomUUID(), createdAt: now, updatedAt: now, ...input, lane: parseLane(input.lane) },
        heroes
      );
      await store.createTierList(tierList, user.id);
      return present(await store.getTierList(tierList.id, user.id), heroes);
    })
  );

  router.get(
    "/tier-lists/:id",
    wrap(async request => {
      const found = await store.getTierList(parseUuid(request.params.id), viewerId(request));
      if (!found) {
        throw notFound("Tier list not found.");
      }
      return present(found, await store.readHeroes());
    })
  );

  // The lane is fixed at creation (changing it would silently drop placements).
  router.put(
    "/tier-lists/:id",
    wrap(async request => {
      const input = parseTierListInput(request.body);
      if (input.lane !== undefined) {
        parseLane(input.lane);
      } // validated, then ignored: the lane never changes
      const expectedVersion = parseExpectedVersion(request.body);
      const heroes = await store.readHeroes();
      const result = await store.updateTierList(
        parseUuid(request.params.id),
        viewerId(request),
        expectedVersion,
        existing =>
          normalizeTierList(
            {
              ...existing,
              name: input.name,
              tiers: input.tiers,
              unranked: input.unranked,
              lane: parseLane(existing.lane),
              createdAt: existing.createdAt
            },
            heroes
          )
      );
      return present(result, heroes);
    })
  );

  router.delete(
    "/tier-lists/:id",
    wrap(async request => {
      const id = parseUuid(request.params.id);
      const found = await store.getTierList(id, viewerId(request));
      if (!found) {
        throw notFound("Tier list not found.");
      }
      if (found.role !== "owner") {
        throw forbidden("Only the creator can delete this tier list.");
      }
      await store.deleteTierList(id, viewerId(request));
      return { deleted: true };
    })
  );

  registerSharingRoutes(router, { store, kind: "tierList", path: "/tier-lists", limiters });
  return router;
}
