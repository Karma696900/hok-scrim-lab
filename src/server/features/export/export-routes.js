import express, { Router } from "express";
import { HttpError, notFound, unauthorized } from "../../platform/errors.js";
import { wrap } from "../../platform/http/async.js";
import { summarize } from "../series/series-summary.js";
import { extractFromFile } from "../series/series-file.js";
import { isFlowborn } from "../heroes/hero-domain.js";
import { parseExportOptions } from "./export-validation.js";
import { parseSeriesFilters, parseSeriesImport } from "../series/series-validation.js";
import { parseUuid } from "../../platform/validation.js";

const send = (response, file) => {
  response.set({
    "Content-Type": file.contentType,
    "Content-Disposition": `attachment; filename="${file.filename}"`,
    "Content-Length": String(file.body.length),
    "Cache-Control": "no-store",
    "X-Export-Series": String(file.count)
  });
  response.end(file.body);
};

/**
 * Series files. Downloads are PDF or PNG only (styled report + the data needed to import it back);
 * imports accept exactly those files. All writes go through the strict validation of parseSeriesImport.
 */
export function createExportRouter({ store, identity, exportService, limiters }) {
  const router = Router();
  const needService = () => {
    if (!exportService) {
      throw new HttpError(503, "export_unavailable", "Export is not available on this server.");
    }
  };

  // One series (anyone who can see it): styled PDF/PNG with an optional note and a chosen file
  // name.
  router.post(
    "/series/:id/export",
    limiters.export,
    wrap(async (request, response) => {
      if (!request.user) {
        throw unauthorized("Nothing to export yet.");
      }
      needService();
      const options = { ...parseExportOptions(request.body), language: request.language };
      const found = await store.getSeries(parseUuid(request.params.id), request.user.id);
      if (!found) {
        throw notFound("Series not found.");
      }
      send(response, await exportService.exportSeries(request.user, found.series, options));
    })
  );

  // The History selection (own series matching the filters), PDF only.
  router.post(
    "/export/pdf",
    limiters.export,
    wrap(async (request, response) => {
      if (!request.user) {
        throw unauthorized("Sign in or create a series first: there is nothing to export yet.");
      }
      needService();
      const body =
        request.body && typeof request.body === "object" && !Array.isArray(request.body)
          ? request.body
          : {};
      const options = {
        ...parseExportOptions(body, { allowPng: false }),
        language: request.language
      };
      send(
        response,
        await exportService.exportFiltered(request.user, parseSeriesFilters(body), options)
      );
    })
  );

  // Import a PDF/PNG generated above. The body is the raw file.
  router.post(
    "/series/import-file",
    limiters.import,
    express.raw({
      type: ["application/pdf", "image/png", "application/octet-stream"],
      limit: "12mb"
    }),
    wrap(async (request, response) => {
      if (!Buffer.isBuffer(request.body) || !request.body.length) {
        throw new HttpError(
          400,
          "invalid_file",
          "Choose a PDF or PNG generated by HOK Global Scrim Lab."
        );
      }
      const envelope = await extractFromFile(request.body);
      const heroes = await store.readHeroes();
      const knownHeroIds = new Set(heroes.map(hero => hero.id));
      const flowbornIds = heroes.filter(isFlowborn).map(hero => hero.id);
      const parsed = envelope.series.map((item, index) => {
        try {
          return parseSeriesImport(item, knownHeroIds, { flowbornIds });
        } catch (error) {
          if (error instanceof HttpError && envelope.series.length > 1) {
            error.seriesNumber = index + 1;
          }
          throw error;
        }
      });
      const user = await identity.ensureUser(request, response);
      const created = [];
      for (const series of parsed) {
        await store.assertQuota("series", user);
        await store.createSeries(series, user.id);
        const stored = await store.getSeries(series.id, user.id);
        created.push(summarize(stored.series, stored.ctx));
      }
      return {
        imported: created.length,
        series: created,
        comment: typeof envelope.comment === "string" ? envelope.comment.slice(0, 500) : ""
      };
    })
  );

  return router;
}
